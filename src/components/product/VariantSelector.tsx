'use client'

import type { Product, Variant } from '@/payload-types'

import { Price } from '@/components/Price'
import { SalePrice } from '@/components/SalePrice'
import { createUrl } from '@/utilities/createUrl'
import { cn } from '@/utilities/cn'
import { calculateDiscountPercentage } from '@/utilities/saleEvents'
import { CheckCircle2 } from 'lucide-react'
import { usePathname, useRouter, useSearchParams } from 'next/navigation'
import React from 'react'

export function VariantSelector({ product }: { product: Product }) {
  const router = useRouter()
  const pathname = usePathname()
  const searchParams = useSearchParams()
  const variants = product.variants?.docs
  const variantTypeDefs = product.variantTypeDefs
  const hasVariants = Boolean(product.enableVariants && variants?.length && variantTypeDefs?.length)

  if (!hasVariants) {
    return null
  }

  return variantTypeDefs?.map((type) => {
    if (!type || typeof type !== 'object') {
      return <React.Fragment key="empty" />
    }

    const options = type.options

    if (!options || !Array.isArray(options) || !options.length) {
      return <React.Fragment key="empty-opts" />
    }

    // Use type.id or a slugified version of label as the param key
    // Defaulting to the ID generated by payload array field
    const optionKey = type.id || String(type.label).toLowerCase().replace(/\s+/g, '-')

    return (
      <div className="flex flex-wrap gap-3" key={type.id || optionKey}>
        {options.map((option) => {
          if (!option || typeof option !== 'object') {
            return <React.Fragment key="empty-opt" />
          }

          const optionID = option.id
          if (!optionID) return <React.Fragment key="empty-opt-id" />

          const optionSearchParams = new URLSearchParams(searchParams.toString())
          optionSearchParams.delete('variant')
          optionSearchParams.delete('image')
          optionSearchParams.set(optionKey, optionID)

          const currentOptions = Array.from(optionSearchParams.values())

          let matchingVariant: Variant | undefined

          if (variants) {
            matchingVariant = variants
              .filter((v): v is Variant => typeof v === 'object')
              .find((v) => {
                if (!v.options || !Array.isArray(v.options)) return false
                
                // Compare variant JSON options array against the selected optionIDs in the URL
                return v.options.every((vo: any) => {
                  return currentOptions.includes(vo.optionId)
                })
              })

            if (matchingVariant) {
              optionSearchParams.set('variant', String(matchingVariant.id))
            }
          }

          const optionUrl = createUrl(pathname, optionSearchParams)
          const isActive = searchParams.get(optionKey) === optionID

          const variantPrice = matchingVariant?.priceInVND ?? null
          const variantHotDeal = (matchingVariant as any)?.hotDealPrice ?? null
          const hasHotDeal = variantHotDeal != null && variantPrice != null && variantHotDeal > 0 && variantHotDeal < variantPrice
          const hotDealPct = hasHotDeal ? calculateDiscountPercentage(variantPrice!, variantHotDeal!) : 0

          return (
            <button
              key={optionID}
              type="button"
              title={option.label}
              onClick={() => router.replace(optionUrl, { scroll: false })}
              className={cn(
                'relative flex min-w-[100px] flex-col items-start rounded-lg border px-4 py-3 text-left transition-colors',
                'hover:border-primary/50',
                isActive ? 'border-primary bg-primary/5' : 'border-border bg-background',
              )}
            >
              {isActive && (
                <CheckCircle2 className="absolute right-2 top-2 size-4 fill-primary text-white" />
              )}
              <span className="text-sm font-medium">{option.label}</span>
              {hasHotDeal ? (
                <span className="text-xs mt-0.5 flex items-center gap-1.5">
                  <SalePrice
                    salePrice={variantHotDeal!}
                    originalPrice={variantPrice!}
                    as="span"
                    className="flex-row items-center gap-1.5"
                    salePriceClassName="text-xs font-semibold text-green-600"
                    originalPriceClassName="text-[10px] text-muted-foreground line-through"
                  />
                  {hotDealPct > 0 && (
                    <span className="rounded bg-green-500 px-1 py-0.5 text-[10px] font-bold text-white">
                      -{hotDealPct}%
                    </span>
                  )}
                </span>
              ) : variantPrice != null ? (
                <span className="text-xs text-muted-foreground mt-0.5">
                  <Price amount={variantPrice} />
                </span>
              ) : null}
            </button>
          )
        })}
      </div>
    )
  })
}
